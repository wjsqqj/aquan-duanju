# -*- coding: utf-8 -*-
"""从 pyvendor/TTEncrypt.py 生成 Go 移植：
1) 类属性表（dword_0..9 / LIST_6B0 / ord_list / rodata / begining）→ ttencrypt_tables.go
2) 寄存器轨迹方法（hex_27E / hex_30A / hex_CF8 / hex_0A2）→ AST 转译为 Go 源码。

Python 侧这些方法只含规整形态（VAR = 表达式 / 下标赋值 / range 循环 / if+break /
append / 列表拼接），可机械转译；值域 ≤ 2^56 → Go 用 uint64。
运行：python scripts/gen_ttencrypt.py（输出写入 native/bridge/hongguov5/）
"""
import ast
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "native" / "bridge" / "hongguo-sidecar" / "pyvendor" / "TTEncrypt.py"
OUT = REPO / "native" / "bridge" / "hongguov5"

sys.path.insert(0, str(SRC.parent))
from TTEncrypt import TT  # noqa: E402

TABLES = {
    "dword_0": ("ttDword0", TT.dword_0), "dword_1": ("ttDword1", TT.dword_1),
    "dword_2": ("ttDword2", TT.dword_2), "dword_3": ("ttDword3", TT.dword_3),
    "dword_4": ("ttDword4", TT.dword_4), "dword_5": ("ttDword5", TT.dword_5),
    "dword_6": ("ttDword6", TT.dword_6), "dword_7": ("ttDword7", TT.dword_7),
    "dword_8": ("ttDword8", TT.dword_8), "dword_9": ("ttDword9", TT.dword_9),
    "LIST_6B0": ("ttLIST6B0", TT.LIST_6B0), "ord_list": ("ttOrdList", TT.ord_list),
    "rodata": ("ttRodata", TT.rodata), "begining": ("ttBegining", TT.begining),
}

# ---- 表格输出 ----

def emit_tables():
    lines = [
        "// Code generated by scripts/gen_ttencrypt.py from pyvendor/TTEncrypt.py; DO NOT EDIT.",
        "",
        "package hongguov5",
        "",
        "// ttencrypt_tables.go — TTEncrypt 类常量表（机械提取，勿手改）。",
    ]
    for name, (goname, values) in TABLES.items():
        if name == "begining":
            lines.append("var " + goname + " = [...]uint32{"
                         + ", ".join(hex(v) for v in values) + "}")
            continue
        lines.append(f"var {goname} = []uint64{{")
        row = []
        for v in values:
            row.append(str(v))
            if len(row) == 12:
                lines.append("\t" + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("\t" + ", ".join(row) + ",")
        lines.append("}")
        lines.append("")
    (OUT / "ttencrypt_tables.go").write_text("\n".join(lines), encoding="utf-8")
    print("tables ->", OUT / "ttencrypt_tables.go")


# ---- AST 转译器 ----

BINOPS = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.BitXor: "^",
          ast.BitOr: "|", ast.BitAnd: "&", ast.FloorDiv: "/", ast.RShift: ">>",
          ast.LShift: "<<"}

TOHEX_SHIFT = re.compile(r"^self\.parseLong\(self\.toHex\((\w+)\) \+ ['\"]((?:0+)*)['\"], 10, 16\)$")


class Transpiler:
    def __init__(self, func_name, go_name, args):
        self.func_name = func_name
        self.go_name = go_name
        self.args = args
        self.body = []

    def translate(self):
        src = Path(SRC).read_text(encoding="utf-8")
        tree = ast.parse(src)
        fn = next(n for n in ast.walk(tree)
                  if isinstance(n, ast.FunctionDef) and n.name == self.func_name)
        # 先扫出全部局部变量名并分类（标量 / 切片）；参数与循环变量不预声明。
        scalar, slice_vars = set(), set()
        for node in ast.walk(fn):
            if isinstance(node, ast.Assign):
                for tgt in node.targets:
                    if isinstance(tgt, ast.Name):
                        if self._is_slice_expr(node.value):
                            slice_vars.add(tgt.id)
                        else:
                            scalar.add(tgt.id)
                    elif isinstance(tgt, ast.Subscript) and isinstance(tgt.value, ast.Name):
                        slice_vars.add(tgt.value.id)
        # 第二遍：concat（含目标名）归切片；int 类型传播（len / 纯 int 运算）。
        loop_vars = set()
        for node in ast.walk(fn):
            if isinstance(node, ast.For) and isinstance(node.target, ast.Name):
                loop_vars.add(node.target.id)
        int_names = set(loop_vars)
        params = set(self.args) | loop_vars
        # 每个名字的多次赋值全部为 int 表达式才判 int（寄存器变量常见“初值 0 + 后续异或”）。
        assigns = {}
        for node in ast.walk(fn):
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                assigns.setdefault(node.targets[0].id, []).append(node.value)
        for _round in range(4):
            for name, values in assigns.items():
                if name in slice_vars or name in params:
                    continue
                if all(self._int_expr(v, int_names) for v in values):
                    int_names.add(name)
            # concat 归类（a = b + [..] / a = b + c）
            for node in ast.walk(fn):
                if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                    name, value = node.targets[0].id, node.value
                    stack = [value]
                    while stack:
                        v = stack.pop()
                        if isinstance(v, ast.BinOp) and isinstance(v.op, ast.Add):
                            for side in (v.left, v.right):
                                if isinstance(side, ast.Name) and side.id in slice_vars:
                                    slice_vars.add(name)
                                elif isinstance(side, ast.BinOp):
                                    stack.append(side)
        # 第三遍：concat 实参中的 Name 也是切片。
        for node in ast.walk(fn):
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                stack = [node.value]
                while stack:
                    v = stack.pop()
                    if isinstance(v, ast.BinOp) and isinstance(v.op, ast.Add):
                        for side in (v.left, v.right):
                            if isinstance(side, ast.Name) and side.id not in int_names:
                                slice_vars.add(side.id)
                            elif isinstance(side, ast.BinOp):
                                stack.append(side)
        scalar -= slice_vars | params | int_names
        slice_vars -= params | int_names
        self.slice_names = slice_vars | set(self.args)
        self.int_names = int_names
        lines = [f"func {self.go_name}(t *ttEngine, {', '.join(a + ' []uint64' for a in self.args)}) []uint64 {{"]
        for name in sorted(scalar):
            lines.append(f"\tvar {name} uint64")
        for name in sorted(self.int_names - slice_vars):
            lines.append(f"\tvar {name} int")
        for name in sorted(slice_vars):
            lines.append(f"\tvar {name} []uint64")
        read_names = {n.id for n in ast.walk(fn) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)}
        written_only = {n.id for n in ast.walk(fn)
                        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)} - read_names
        for name in sorted(slice_vars & written_only):
            lines.append(f"\t_ = {name} // python 侧计算后未使用，保留对齐")
        for node in fn.body:
            # 末尾 return 由 _guess_return 统一补（避免重复 return 触发 unreachable）。
            if isinstance(node, ast.Return):
                continue
            self.emit_stmt(node, lines, 1)
        lines.append("\treturn " + self._guess_return(fn))
        lines.append("}")
        return "\n".join(lines)

    def _guess_return(self, fn):
        for node in ast.walk(fn):
            if isinstance(node, ast.Return) and isinstance(node.value, ast.Name):
                return node.value.id
        return self.args[0]

    def _int_expr(self, node, int_names):
        """表达式值域是否为 Go int：len(...)、int 字面量、已知名与它们的四则运算。"""
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "len":
            return True
        if isinstance(node, ast.Constant) and isinstance(node.value, int):
            return True
        if isinstance(node, ast.Name):
            return node.id in int_names
        if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult, ast.FloorDiv)):
            return self._int_expr(node.left, int_names) and self._int_expr(node.right, int_names)
        return False

    def _is_slice_node(self, node):
        if isinstance(node, ast.Name):
            return node.id in self.slice_names
        return self._is_slice_expr(node)

    def _is_slice_expr(self, value):
        if isinstance(value, (ast.List, ast.ListComp)):
            return True
        if isinstance(value, ast.BinOp) and isinstance(value.op, ast.Add):
            return self._is_slice_expr(value.left) or self._is_slice_expr(value.right)
        if isinstance(value, ast.Call):
            name = self._attr_name(value.func)
            if name in ("hex_list", "hex_C52", "dump_list", "calculate",
                        "convertLongList", "hex_27E", "hex_30A", "hex_CF8", "hex_0A2"):
                return True
            if isinstance(value.func, ast.Attribute) and value.func.attr == "append":
                return True
        return False

    def emit_stmt(self, node, lines, depth):
        pad = "\t" * depth
        if isinstance(node, ast.Assign):
            tgt = node.targets[0]
            if isinstance(tgt, ast.Name):
                lines.append(f"{pad}{tgt.id} = {self.expr(node.value)}")
            elif isinstance(tgt, ast.Subscript):
                lines.append(f"{pad}{tgt.value.id}[int({self.expr(tgt.slice)})] = {self.expr(node.value)}")
            else:
                raise SystemExit(f"unsupported assign target: {ast.dump(tgt)}")
        elif isinstance(node, ast.AugAssign):
            op = BINOPS[type(node.op)]
            tgt = node.target
            lines.append(f"{pad}{tgt.id} = {tgt.id} {op} {self.expr(node.value)}")
        elif isinstance(node, ast.For):
            var = node.target.id
            n = node.iter.args[0]
            lines.append(f"{pad}for {var} = 0; {var} < {self.expr(n)}; {var}++ {{")
            for sub in node.body:
                self.emit_stmt(sub, lines, depth + 1)
            lines.append(f"{pad}}}")
        elif isinstance(node, ast.If):
            cond = self.cond(node.test)
            lines.append(f"{pad}if {cond} {{")
            for sub in node.body:
                self.emit_stmt(sub, lines, depth + 1)
            if node.orelse:
                lines.append(f"{pad}}} else {{")
                for sub in node.orelse:
                    self.emit_stmt(sub, lines, depth + 1)
            lines.append(f"{pad}}}")
        elif isinstance(node, ast.Break):
            lines.append(f"{pad}break")
        elif isinstance(node, ast.Expr):
            v = node.value
            # 裸 append 靠副作用：Go 侧必须回写（append 可能扩容）。
            if isinstance(v, ast.Call) and isinstance(v.func, ast.Attribute)                     and v.func.attr == "append" and isinstance(v.func.value, ast.Name):
                tgt = v.func.value.id
                lines.append(f"{pad}{tgt} = append({tgt}, {self.expr(v.args[0])})")
        elif isinstance(node, ast.Return):
            lines.append(f"{pad}return {self.expr(node.value)}")
        else:
            raise SystemExit(f"unsupported stmt in {self.func_name}: {ast.dump(node)}")

    def cond(self, test):
        if isinstance(test, ast.Compare):
            op = test.ops[0]
            sym = {"Eq": "==", "Gt": ">", "Lt": "<", "NotEq": "!=", "GtE": ">=", "LtE": "<="}[type(op).__name__]
            return f"{self.expr(test.left)} {sym} {self.expr(test.comparators[0])}"
        return self.expr(test)

    def expr(self, node):
        if isinstance(node, ast.Constant):
            return str(node.value)
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Attribute):
            if isinstance(node.value, ast.Name) and node.value.id == "self":
                table_map = {"dword_0": "ttDword0", "dword_1": "ttDword1", "dword_2": "ttDword2",
                             "dword_3": "ttDword3", "dword_4": "ttDword4", "dword_5": "ttDword5",
                             "dword_6": "ttDword6", "dword_7": "ttDword7", "dword_8": "ttDword8",
                             "dword_9": "ttDword9", "LIST_6B0": "ttLIST6B0", "rodata": "ttRodata",
                             "ord_list": "ttOrdList", "begining": "ttBegining"}
                if node.attr in table_map:
                    return table_map[node.attr]
        if isinstance(node, ast.BinOp):
            op = BINOPS[type(node.op)]
            left, right = node.left, node.right
            if op == "+" and (self._is_slice_node(left) or self._is_slice_node(right)):
                # python a + b 生成新列表；Go 侧嵌套 append（spread 后不能再跟元素）。
                parts = []
                for side in (left, right):
                    if isinstance(side, ast.List):
                        parts += [self.expr(e) for e in side.elts]
                    elif self._is_slice_node(side):
                        parts.append(self.expr(side) + "...")
                expr = "[]uint64{}"
                for part in parts:
                    expr = f"append({expr}, {part})"
                return expr

            return f"({self.expr(left)} {op} {self.expr(right)})"
        if isinstance(node, ast.Subscript):
            return f"{self.expr(node.value)}[int({self.expr(node.slice)})]"
        if isinstance(node, ast.List):
            return "[]uint64{" + ", ".join(self.expr(e) for e in node.elts) + "}"
        if isinstance(node, ast.Call):
            return self.call(node)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return "-" + self.expr(node.operand)
        raise SystemExit(f"unsupported expr: {ast.dump(node)}")

    def call(self, node):
        func = node.func
        # int(...) 包裹 → 直接展开内部表达式。
        if isinstance(func, ast.Name) and func.id == "int":
            return self.expr(node.args[0])
        if isinstance(func, ast.Name) and func.id == "len":
            return f"len({self.expr(node.args[0])})"
        # parseLong(toHex(X) + "000...", 10, 16) → X << (4*len)
        if isinstance(func, ast.Attribute) and func.attr == "parseLong":
            pattern = TOHEX_SHIFT.match(self._render(node))
            if pattern:
                var, suffix = pattern.group(1), pattern.group(2)
                return f"(({var}) << {4 * len(suffix)})"
        if isinstance(func, ast.Attribute):
            recv = func.value
            if isinstance(recv, ast.Name) and recv.id == "self":
                name = func.attr
                args = ", ".join(self.expr(a) for a in node.args)
                if name in ("dword_0", "dword_1", "dword_2", "dword_3", "dword_4",
                            "dword_5", "dword_6", "dword_7", "dword_8", "dword_9",
                            "LIST_6B0", "rodata"):
                    raise SystemExit(f"unexpected table call {name}")
                return f"t.{snake(name)}({args})"
            if isinstance(recv, ast.Name):
                # 列表方法：list_478.append(R6) → append(list_478, R6)
                if func.attr == "append":
                    return f"append({recv.id}, {self.expr(node.args[0])})"
                if func.attr == "copy":
                    raise SystemExit("list.copy unsupported")
        raise SystemExit(f"unsupported call: {ast.dump(node)}")

    def _render(self, node):
        return ast.unparse(node)

    def _attr_name(self, func):
        return func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", "")


NAME_MAP = {
    "dump_list": "dumpList", "hex_list": "hexList", "hex_C52": "hexC52",
    "handle_ending": "handleEnding", "calculate": "calculate",
    "hex_27E": "ttHex27E", "hex_30A": "ttHex30A",
    "hex_CF8": "ttHexCF8", "hex_0A2": "ttHex0A2",
}


def snake(name):
    return NAME_MAP.get(name, name)


def emit_methods():
    specs = [
        ("hex_27E", "ttHex27E", ["param_list"]),
        ("hex_30A", "ttHex30A", ["param_list", "list_3B8"]),
        ("hex_CF8", "ttHexCF8", ["param_list"]),
        ("hex_0A2", "ttHex0A2", ["content", "list_740", "list_55C"]),
    ]
    out = [
        "// Code generated by scripts/gen_ttencrypt.py from pyvendor/TTEncrypt.py; DO NOT EDIT.",
        "// 寄存器轨迹方法机械转译：变量名与语句顺序与 Python 逐行对应，值域 uint64。",
        "",
        "package hongguov5",
        "",
    ]
    for func_name, go_name, args in specs:
        out.append(Transpiler(func_name, go_name, args).translate())
        out.append("")
    (OUT / "ttencrypt_trace.go").write_text("\n".join(out), encoding="utf-8")
    print("methods ->", OUT / "ttencrypt_trace.go")


def emit_json_tables():
    # 冗余保险：同时把表落成 JSON 供以后核对。
    data = {k: v for k, v in TABLES.items()}
    (OUT / "testdata" / "ttencrypt_tables.json").write_text(
        json.dumps(data), encoding="utf-8")


if __name__ == "__main__":
    (OUT / "testdata").mkdir(parents=True, exist_ok=True)
    emit_tables()
    emit_methods()
    emit_json_tables()
